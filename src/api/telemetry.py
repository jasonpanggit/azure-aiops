"""Telemetry for the Operations API.

Records request counts, latency, authorization outcomes, and orchestration
stage behaviour through the OpenTelemetry metrics API already used across the
intelligence engines. No request payloads, headers, principals, or scope values
are recorded -- only low-cardinality dimensions -- so telemetry can never
become a secret sink.

Orchestration metrics take that further. Every attribute is projected through a
controlled vocabulary before it reaches an instrument: a value that is not a
declared enum member or a manifest identifier is emitted as ``other``. That
makes the privacy property structural rather than a convention a future caller
has to remember, and it bounds series cardinality at the same time.
"""

from __future__ import annotations

import logging
import time
from functools import lru_cache
from typing import Any

from opentelemetry import metrics

from operations.exposure_metrics import ExposureMetrics
from operations.investigation_thread_store import (
    DURABILITY_DURABLE,
    DURABILITY_MEMORY_ONLY,
    OBSERVATION_CURRENT,
    OBSERVATION_HISTORICAL,
    THREAD_MISS_REASONS,
)
from operations.specialist_manifest import load_specialist_manifest

_UNCONTROLLED = "other"
_MAX_COUNT = 1_000_000
_LOGGER = logging.getLogger(__name__)

_STAGES = frozenset(
    {"plan", "specialist", "synthesis", "persist", "total"}
)
_TOOL_STATUSES = frozenset({"ok", "empty", "partial", "unavailable", "denied"})
_POLICY_STATUSES = frozenset({"accepted", "fallback"})
_OBSERVATION_STATUSES = frozenset({OBSERVATION_CURRENT, OBSERVATION_HISTORICAL})
_BUDGET_OUTCOMES = frozenset({"within_budget", "exhausted"})
_DURABILITY = frozenset({DURABILITY_DURABLE, DURABILITY_MEMORY_ONLY})
_THREAD_OUTCOMES = frozenset({"created", "continued", "imported", *THREAD_MISS_REASONS})
_SYNTHESIS_DECISIONS = frozenset(
    {"explicit_intent", "multi_domain", "single_domain", "no_cited_findings"}
)
_SYNTHESIS_STATUSES = frozenset({"skipped", "synthesized", "degraded"})
#: Fallback reasons are produced by the orchestration policy, so the vocabulary
#: is closed. A compound reason keeps only its leading code.
_FALLBACK_REASONS = frozenset(
    {
        "planner_unavailable",
        "planner_timeout",
        "planner_parse_error",
        "candidate_rejected",
        "unsupported_intent",
        "unsupported_tool_hint",
        "invalid_hint_arguments",
        "missing_required_arguments",
        "none",
    }
)


@lru_cache(maxsize=1)
def _manifest_vocabulary() -> tuple[frozenset[str], frozenset[str]]:
    """Load controlled IDs lazily; telemetry must never block API startup."""

    try:
        manifest = load_specialist_manifest()
    except (OSError, TypeError, ValueError):
        _LOGGER.warning("orchestration telemetry manifest unavailable", exc_info=True)
        return frozenset(), frozenset()
    return frozenset(manifest.specialist_ids), frozenset(
        manifest.operations_tool_names()
    )


def _controlled(value: Any, allowed: frozenset[str]) -> str:
    """Project one attribute onto its controlled vocabulary.

    Anything outside the vocabulary becomes ``other`` rather than being
    dropped: the event still counts, but a question, an argument, a principal,
    or a resource id can never reach an exported series.
    """

    candidate = str(value or "").strip()
    return candidate if candidate in allowed else _UNCONTROLLED


def _fallback_code(reason: Any) -> str:
    """Reduce ``candidate_rejected:mutation_forbidden`` to its policy codes."""

    candidate = str(reason or "none").strip()
    head, _, detail = candidate.partition(":")
    code = _controlled(head, _FALLBACK_REASONS)
    if code == _UNCONTROLLED or not detail:
        return code
    # The violation code is generated by the policy, not by a caller, so it is
    # safe to keep and is what makes a rejection actionable.
    return f"{code}:{detail}" if detail.replace("_", "").isalnum() else code


def _count(value: Any) -> int:
    try:
        return max(0, min(int(value), _MAX_COUNT))
    except (TypeError, ValueError):
        return 0


def _duration(value: Any) -> float:
    try:
        return max(0.0, float(value))
    except (TypeError, ValueError):
        return 0.0


class OrchestrationTelemetry:
    """Low-cardinality metrics for governed orchestration.

    Operators need to see how work was delegated, when it fell back, how much
    evidence a turn produced, how long each stage took, and whether the budget
    ran out. None of those questions require the question text, the tool
    arguments, the caller, the resources involved, or the model's reasoning, so
    none of them are accepted here.
    """

    def __init__(self, meter: Any = None) -> None:
        self._meter = meter or metrics.get_meter("aiops.orchestration")
        self._delegations = self._meter.create_counter(
            "aiops.orchestration.delegation",
            description="Specialist delegations by stage, specialist, tool and status",
        )
        self._fallbacks = self._meter.create_counter(
            "aiops.orchestration.fallback",
            description="Deterministic fallbacks by policy reason code",
        )
        self._evidence = self._meter.create_counter(
            "aiops.orchestration.evidence",
            description="Evidence items by status and observation status",
        )
        self._stage_latency = self._meter.create_histogram(
            "aiops.orchestration.stage.duration",
            unit="ms",
            description="Orchestration stage latency",
        )
        self._budget = self._meter.create_counter(
            "aiops.orchestration.budget",
            description="Wall-clock budget outcomes",
        )
        self._budget_latency = self._meter.create_histogram(
            "aiops.orchestration.budget.duration",
            unit="ms",
            description="Wall-clock consumed per turn",
        )
        self._synthesis = self._meter.create_counter(
            "aiops.orchestration.synthesis",
            description="Executive synthesis admission decisions and outcomes",
        )
        self._threads = self._meter.create_counter(
            "aiops.orchestration.thread",
            description="Continuity outcomes by durability",
        )

    def record_delegation(
        self,
        *,
        stage: str,
        specialist_id: str,
        tool: str,
        status: str,
        policy_status: str,
        duration_ms: float,
    ) -> None:
        attributes = {
            "stage": _controlled(stage, _STAGES),
            "specialist_id": _controlled(
                specialist_id, _manifest_vocabulary()[0]
            ),
            "tool": _controlled(tool, _manifest_vocabulary()[1]),
            "status": _controlled(status, _TOOL_STATUSES),
            "policy_status": _controlled(policy_status, _POLICY_STATUSES),
        }
        self._delegations.add(1, attributes)
        self._stage_latency.record(_duration(duration_ms), attributes)

    def record_fallback(self, *, reason: str) -> None:
        self._fallbacks.add(1, {"reason": _fallback_code(reason)})

    def record_evidence(
        self,
        *,
        status: str,
        observation_status: str,
        count: int,
    ) -> None:
        self._evidence.add(
            _count(count),
            {
                "status": _controlled(status, _TOOL_STATUSES),
                "observation_status": _controlled(
                    observation_status, _OBSERVATION_STATUSES
                ),
            },
        )

    def record_stage_latency(self, *, stage: str, duration_ms: float) -> None:
        self._stage_latency.record(
            _duration(duration_ms),
            {"stage": _controlled(stage, _STAGES)},
        )

    def record_budget(self, *, outcome: str, duration_ms: float) -> None:
        attributes = {"outcome": _controlled(outcome, _BUDGET_OUTCOMES)}
        self._budget.add(1, attributes)
        self._budget_latency.record(_duration(duration_ms), attributes)

    def record_synthesis(
        self,
        *,
        decision: str,
        status: str,
        domain_count: int,
    ) -> None:
        self._synthesis.add(
            1,
            {
                "decision": _controlled(decision, _SYNTHESIS_DECISIONS),
                "status": _controlled(status, _SYNTHESIS_STATUSES),
                "domain_count": _count(domain_count),
            },
        )

    def record_thread(self, *, outcome: str, durability: str) -> None:
        self._threads.add(
            1,
            {
                "outcome": _controlled(outcome, _THREAD_OUTCOMES),
                "durability": _controlled(durability, _DURABILITY),
            },
        )


class ApiTelemetry:
    def __init__(self, meter: Any = None) -> None:
        self._meter = meter or metrics.get_meter("aiops.api")
        self.exposure = ExposureMetrics(meter=self._meter)
        self.orchestration = OrchestrationTelemetry(meter=self._meter)
        self._requests = self._meter.create_counter(
            "aiops.api.requests",
            description="Operations API requests by route, method and status class",
        )
        self._latency = self._meter.create_histogram(
            "aiops.api.request.duration",
            unit="ms",
            description="Operations API request latency",
        )
        self._denied = self._meter.create_counter(
            "aiops.api.authorization.denied",
            description="Requests rejected by authentication or authorization",
        )

    def record_request(
        self, *, route: str, method: str, status_code: int, duration_ms: float
    ) -> None:
        attributes = {
            "route": route,
            "method": method,
            # Status class only: avoids high-cardinality per-status series.
            "status_class": f"{status_code // 100}xx",
        }
        self._requests.add(1, attributes)
        self._latency.record(max(duration_ms, 0.0), attributes)

    def record_denied(self, *, route: str, reason: str) -> None:
        self._denied.add(1, {"route": route, "reason": reason})


class Timer:
    """Wall-clock timer in milliseconds."""

    def __init__(self, clock=time.monotonic) -> None:
        self._clock = clock
        self._start = clock()

    def elapsed_ms(self) -> float:
        return (self._clock() - self._start) * 1000.0
