API_TITLE = "AIOps Operations API"
API_VERSION = "1.0.0"
API_DESCRIPTION = """
Backend for the Azure AI Operations Workbench.

Every response is an envelope of `data`, `evidence`, and `scope`. Evidence
records the source engine, source table, timestamp, subscription connection,
resource id, confidence, and freshness for the data returned.

Reads are composed from the durable Semantic Knowledge Layer and request-time
operational providers. Mutable operational facts are not generated by AIOps
semantic snapshots.
"""
logger = logging.getLogger("aiops.api")
_CORRELATION_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]{7,127}$")
_REMEDIATION_PLANNER_REFRESH_INTERVAL_SECONDS = 30
_ERROR_RESPONSES = {
    str(status): {
        "description": description,
        "content": {
            "application/json": {"schema": {"$ref": "#/components/schemas/ErrorModel"}}
        },
    }
    for status, description in {
        400: "Invalid request",
        401: "Unauthenticated",
        403: "Forbidden",
        404: "Not found",
        409: "Conflict",
        500: "Internal error",
        501: "Not implemented",
        502: "Upstream unavailable",
        503: "Secret unavailable",
    }.items()
}


def _route_label(request: Request) -> str:
    """Templated path (not the concrete URL) to keep telemetry low-cardinality."""
    route = request.scope.get("route")
    return getattr(route, "path", None) or "unmatched"


def _correlation_id(request: Request) -> str:
    value = str(request.headers.get("x-correlation-id") or "").strip()
    return value if _CORRELATION_ID.fullmatch(value) else uuid.uuid4().hex


def _error_body(error: ApiError, request: Request) -> dict[str, Any]:
    return error.to_dict(correlation_id=getattr(request.state, "correlation_id", ""))


def _register_openapi(app: FastAPI) -> None:
    """Publish stable success/error envelopes and auth requirements for clients."""

    def custom_openapi() -> dict[str, Any]:
        if app.openapi_schema:
            return app.openapi_schema
        schema = get_openapi(
            title=app.title,
            version=app.version,
            description=app.description,
            routes=app.routes,
        )
        components = schema.setdefault("components", {})
        schemas = components.setdefault("schemas", {})
        for model in (EnvelopeModel, ErrorModel):
            model_schema = model.model_json_schema(
                ref_template="#/components/schemas/{model}"
            )
            schemas.update(model_schema.pop("$defs", {}))
            schemas[model.__name__] = model_schema
        components.setdefault("securitySchemes", {})["bearerAuth"] = {
            "type": "http",
            "scheme": "bearer",
            "bearerFormat": "Opaque token",
            "description": (
                "Bearer token for local development. Gateway deployments validate "
                "identity upstream and map it to explicitly configured grants."
            ),
        }
        for path, path_operations in schema["paths"].items():
            for method, operation in path_operations.items():
                if method not in {"get", "post", "patch", "put", "delete"}:
                    continue
                if path not in {"/health", "/ready"}:
                    operation["security"] = [{"bearerAuth": []}]
                responses = operation.setdefault("responses", {})
                for status in ("200", "201"):
                    if status in responses:
                        responses[status].setdefault("content", {})[
                            "application/json"
                        ] = {"schema": {"$ref": "#/components/schemas/EnvelopeModel"}}
                responses.update(
                    {
                        status: detail
                        for status, detail in _ERROR_RESPONSES.items()
                        if status not in responses
                    }
                )
        app.openapi_schema = schema
        return schema

    app.openapi = custom_openapi


def _start_background_refresh(app: FastAPI, context: ApiContext) -> None:
    """Refresh providers on a dedicated background thread.

    Provider loaders can perform slow, rate-limited network calls (NVD/MSRC
    CVE enrichment, Fabric OneLake reads). Relying on request threads (probe
    or otherwise) to drive refreshes means a slow loader blocks whatever
    request happened to trigger it -- including liveness/readiness probes,
    which Container Apps kills on timeout. This timer thread is the only
    owner of provider cache-key, freshness, metadata, and loader I/O;
    request-time `ProviderRuntime.get()` calls only read the last completed
    in-memory publication.
    """
    provider_runtime = context.provider_runtime
    if provider_runtime is None:
        return
    stop_event = threading.Event()
    interval = max(provider_runtime.refresh_interval_seconds, 5)

    def _loop() -> None:
        # First pass forces a refresh immediately (do not wait a full
        # interval before the process has any provider data at all), then
        # settles into the normal interval-based cadence.
        try:
            provider_runtime.refresh(force=True, blocking=True)
        except Exception:
            logger.exception("background_provider_refresh_failed")
        while not stop_event.wait(interval):
            try:
                provider_runtime.refresh(blocking=True)
            except Exception:
                logger.exception("background_provider_refresh_failed")

    thread = threading.Thread(
        target=_loop, name="provider-refresh", daemon=True
    )
    thread.start()
    app.state.provider_refresh_stop = stop_event
    app.state.provider_refresh_thread = thread

    @app.on_event("shutdown")
    def _stop_background_refresh() -> None:
        stop_event.set()
        thread.join(timeout=5)


def _refresh_remediation_planner(context: ApiContext) -> None:
    """Refresh the all-subscription remediation planner outside request handling."""
    provider = context.hybrid_remediation_provider
    if provider is None:
        return
    subscriptions = {
        str(connection.subscription_id)
        for connection in context.onboarding.registry.list(include_disabled=False)
        if str(connection.subscription_id)
    }
    if subscriptions:
        provider(sorted(subscriptions))


def _start_remediation_planner_refresh(app: FastAPI, context: ApiContext) -> None:
    """Warm the short-lived remediation cache before it can block a page request."""
    if context.hybrid_remediation_provider is None:
        return

    @app.on_event("startup")
    def _start() -> None:
        try:
            _refresh_remediation_planner(context)
        except Exception:
            logger.exception("remediation_planner_warmup_failed")

        stop_event = threading.Event()

        def _loop() -> None:
            # The provider rebuilds only after its 30-second TTL expires.
            # Polling sooner would return the cached value and postpone the
            # actual refresh until the following interval.
            while not stop_event.wait(_REMEDIATION_PLANNER_REFRESH_INTERVAL_SECONDS):
                try:
                    _refresh_remediation_planner(context)
                except Exception:
                    logger.exception("remediation_planner_refresh_failed")

        thread = threading.Thread(
            target=_loop, name="remediation-planner-refresh", daemon=True
        )
        thread.start()
        app.state.remediation_planner_refresh_stop = stop_event
        app.state.remediation_planner_refresh_thread = thread

    @app.on_event("shutdown")
    def _stop() -> None:
        stop_event = getattr(app.state, "remediation_planner_refresh_stop", None)
        thread = getattr(app.state, "remediation_planner_refresh_thread", None)
        if stop_event is not None:
            stop_event.set()
        if thread is not None:
            thread.join(timeout=5)


def _start_verification_coordinator(app: FastAPI, context: ApiContext) -> None:
    """Drive every due remediation execution on a dedicated background thread.

    The autonomous half of Recommendation 3 (CR-03): an execution's
    terminal status must not depend on a browser tab staying open. This
    mirrors :func:`_start_background_refresh` exactly -- a bounded poll
    interval, a stop event, per-pass error isolation (one failing record,
    or the whole pass, never crashes the loop or blocks the next due
    record), and a bounded-timeout shutdown join. A context built without
    the provider (e.g. some test contexts) safely starts no thread at all.
    """
    if context.verification_coordinator_provider is None:
        return
    try:
        coordinator = context.verification_coordinator_provider()
    except Exception:
        # WR-03: matches every per-pass call inside _loop() below (and
        # _start_background_refresh's identical pattern) -- a remediation-
        # subsystem-local construction failure must never escalate into a
        # full API-startup failure.
        logger.exception("remediation_verification_coordinator_construction_failed")
        return
    stop_event = threading.Event()
    # Shorter than the provider-refresh interval: per-record verification
    # backoff is already bounded at 60s (execution_service._next_backoff_seconds),
    # so a tighter coordinator cadence lets a just-submitted execution's
    # immediate (next_verification_at == now) first pass be picked up
    # promptly without waiting a full provider-refresh cycle.
    interval = 10

    def _loop() -> None:
        # Mirrors _start_background_refresh: run one pass immediately (do
        # not wait a full interval before a freshly-restarted process picks
        # up already-due work), then settle into the normal cadence.
        try:
            coordinator.run_once()
        except Exception:
            logger.exception("remediation_verification_pass_failed")
        while not stop_event.wait(interval):
            try:
                coordinator.run_once()
            except Exception:
                logger.exception("remediation_verification_pass_failed")

    thread = threading.Thread(
        target=_loop, name="remediation-verification-coordinator", daemon=True
    )
    thread.start()
    app.state.verification_coordinator_stop = stop_event
    app.state.verification_coordinator_thread = thread

    @app.on_event("shutdown")
    def _stop_verification_coordinator() -> None:
        stop_event.set()
        thread.join(timeout=5)


def create_app(context: ApiContext | None = None, **kwargs: Any) -> FastAPI:
    """Build the API.

    When no context is supplied one is assembled from the environment (see
    :mod:`api.runtime`), so ``uvicorn --factory api.app:create_app`` serves a
    working API instead of failing on every request.
    """
    if context is None:
        from .runtime import build_context

        context = build_context()
    app = FastAPI(
        title=API_TITLE,
        version=API_VERSION,
        description=API_DESCRIPTION,
        **kwargs,
    )
    app.state.context = context
    _start_background_refresh(app, context)
    _start_remediation_planner_refresh(app, context)
    _start_verification_coordinator(app, context)
    configured_origins = os.environ.get(
        "AIOPS_API_CORS_ORIGINS",
        "http://localhost:3000,http://127.0.0.1:3000",
    )
    app.add_middleware(
        CORSMiddleware,
        allow_origins=[origin.strip() for origin in configured_origins.split(",") if origin.strip()],
        allow_origin_regex=r"^https?://(localhost|127\.0\.0\.1)(:\d+)?$",
        allow_credentials=True,
        allow_methods=["*"],
        allow_headers=["*"],
        expose_headers=["X-Correlation-ID"],
    )
    _register_openapi(app)
    telemetry = context.telemetry

    app.include_router(connections.router)
    app.include_router(changes.router)
    app.include_router(fabric_medallion.router)
    app.include_router(compliance_routes.router)
    app.include_router(context_routes.router)
    app.include_router(copilot_routes.router)
    app.include_router(graph.router)
    app.include_router(inventory.router)
    app.include_router(governance_routes.router)
    app.include_router(multi_agent.router)
    app.include_router(mcp_routes.router)
    app.include_router(network.router)
    app.include_router(ontology_discovery.router)
    app.include_router(operations.router)
    app.include_router(overview.router)
    app.include_router(service_portfolio.router)
    app.include_router(patching.router)
    app.include_router(planned.router)
    app.include_router(remediation_routes.router)
    app.include_router(resource_health_routes.router)
    # Imported here rather than at module scope: the pre-deployment engine
    # imports ``api.scope`` and ``api.evidence``, so a top-level import would
    # make ``import intelligence.predeploy`` circular.
    from .routers import predeploy

    app.include_router(predeploy.router)
    app.include_router(twin.router)
    app.include_router(vulnerability.router)
    from .routers import situations as situation_routes

    app.include_router(situation_routes.router)

    class _ObserveMiddleware:
        """Pure ASGI request/response observer.

        This deliberately avoids ``@app.middleware("http")``, which Starlette
        implements via ``BaseHTTPMiddleware``. That base class runs the
        downstream app in a separate task and re-raises any exception through
        ``call_next`` *even after* our own ``@app.exception_handler`` already
        produced and sent a valid JSON error response -- uvicorn then logs
        "Exception in ASGI application" and tears down the connection after
        the body was written, which manifests to browser `fetch()` callers as
        a raw network failure instead of the intended 404/500 JSON. A plain
        ASGI middleware observes the same `send` callable the handlers use,
        so it never re-raises an already-handled exception.
        """

        def __init__(self, inner_app: FastAPI) -> None:
            self.app = inner_app

        async def __call__(self, scope, receive, send):
            if scope["type"] != "http":
                await self.app(scope, receive, send)
                return

            request = Request(scope, receive=receive)
            timer = Timer()
            correlation_id = _correlation_id(request)
            request.state.correlation_id = correlation_id
            status_holder: dict[str, int] = {}

            async def send_wrapper(message):
                if message["type"] == "http.response.start":
                    status_holder["status_code"] = message["status"]
                    headers = message.setdefault("headers", [])
                    headers.append((b"x-correlation-id", correlation_id.encode("latin-1")))
                await send(message)

            try:
                await self.app(scope, receive, send_wrapper)
            except Exception:
                # The exception handlers below already own the response body
                # for domain exceptions; this only fires for a genuine
                # unhandled crash, so record it and re-raise unchanged.
                telemetry.record_request(
                    route=_route_label(request),
                    method=request.method,
                    status_code=500,
                    duration_ms=timer.elapsed_ms(),
                )
                logger.error(
                    "api_request_failed correlation_id=%s route=%s method=%s",
                    correlation_id,
                    _route_label(request),
                    request.method,
                )
                raise

            route = _route_label(request)
            status_code = status_holder.get("status_code", 500)
            telemetry.record_request(
                route=route,
                method=request.method,
                status_code=status_code,
                duration_ms=timer.elapsed_ms(),
            )
            if status_code in (401, 403):
                telemetry.record_denied(route=route, reason=str(status_code))
            logger.info(
                "api_request correlation_id=%s route=%s method=%s status=%s duration_ms=%.2f",
                correlation_id,
                route,
                request.method,
                status_code,
                timer.elapsed_ms(),
            )

    app.add_middleware(_ObserveMiddleware)

    @app.exception_handler(ApiError)
    async def _api_error(request: Request, exc: ApiError) -> JSONResponse:
        return JSONResponse(status_code=exc.status_code, content=_error_body(exc, request))

    @app.exception_handler(RequestValidationError)
    async def _validation_error(
        request: Request, exc: RequestValidationError
    ) -> JSONResponse:
        # Report *which* fields failed and why, but never echo the submitted
        # value: a rejected payload can still contain secret material.
        fields = [
            {
                "field": ".".join(str(part) for part in error.get("loc", ())[1:]),
                "reason": str(error.get("type", "invalid")),
            }
            for error in exc.errors()
        ]
        error = ApiError(
            ErrorCode.INVALID_REQUEST,
            "Request validation failed",
            {"fields": fields},
        )
        return JSONResponse(status_code=error.status_code, content=_error_body(error, request))

    async def _domain_error(request: Request, exc: Exception) -> JSONResponse:
        error = translate(exc)
        logger.warning(
            "api_domain_error correlation_id=%s error_code=%s",
            getattr(request.state, "correlation_id", ""),
            error.code,
        )
        return JSONResponse(status_code=error.status_code, content=_error_body(error, request))

    # Registered per concrete base class rather than relying on the catch-all
    # ``Exception`` handler below. Starlette routes an ``Exception`` handler to
    # ServerErrorMiddleware, which *always* re-raises after producing the
    # response ("We always continue to raise the exception") -- so a plain
    # 404 such as ConnectionNotFoundError still printed a full traceback and
    # tore down the connection. These handlers live in ExceptionMiddleware,
    # which returns the response without re-raising.
    for _domain_exc in (
        LookupError,
        ValueError,
        TypeError,
        PermissionError,
        NotImplementedError,
        OnboardingError,
        SecretNotFoundError,
        SecretStorageError,
    ):
        app.add_exception_handler(_domain_exc, _domain_error)

    @app.exception_handler(Exception)
    async def _unhandled(request: Request, exc: Exception) -> JSONResponse:
        error = translate(exc)
        logger.error(
            "api_unhandled_error correlation_id=%s error_code=%s",
            getattr(request.state, "correlation_id", ""),
            error.code,
        )
        return JSONResponse(status_code=error.status_code, content=_error_body(error, request))

    @app.get("/health", tags=["meta"], summary="Liveness and provider state")
    def health() -> dict[str, Any]:
        runtime_health = (
            context.provider_runtime.health(refresh=False)
            if context.provider_runtime is not None
            else {
                "readiness": "ready" if context.semantic_provider else "degraded",
                "ontology_version": "",
                "freshness": "",
                "last_discovery_run": "",
                "last_ontology_publication": "",
                "degraded_reason": "",
                "providers": {
                    "semantic": {
                        "state": "ready" if context.semantic_provider else "disabled",
                        "loaded": context.semantic_provider is not None,
                    }
                },
            }
        )
        authorization_health = canary_authorization_health()
        if authorization_health["status"] == "denied":
            runtime_health = {
                **runtime_health,
                "readiness": "degraded",
                "degraded_reason": (
                    "Copilot canary authorization denied: "
                    f"{authorization_health['reason']}"
                ),
            }
        semantic = runtime_health["providers"].get("semantic", {})
        return {
            "status": "ok",
            "version": API_VERSION,
            "semantic_snapshot_loaded": bool(semantic.get("loaded")),
            "copilot_canary_authorization": authorization_health,
            **runtime_health,
        }

    @app.get("/ready", tags=["meta"], summary="Provider readiness")
    def readiness() -> JSONResponse:
        if context.provider_runtime is not None:
            # Never block this probe request behind a slow/rate-limited
            # provider loader (e.g. NVD CVE enrichment): if a refresh is
            # already running (background timer or a concurrent probe),
            # `blocking=False` skips waiting and serves the last known
            # state instead. Container Apps kills the container if a probe
            # doesn't respond within its timeout, so a blocking refresh here
            # can turn a slow upstream dependency into a crash loop.
            context.provider_runtime.refresh(blocking=False)
        body = health()
        ready = body["readiness"] in {"ready", "partial", "stale"}
        return JSONResponse(status_code=200 if ready else 503, content=body)

    @app.post(
        "/api/v1/runtime/refresh",
        tags=["meta"],
        summary="Refresh configured runtime providers",
    )
    def refresh_runtime(_principal: OperatePrincipal) -> dict[str, Any]:
        if context.provider_runtime is None:
            raise ApiError(
                ErrorCode.PROVIDER_UNAVAILABLE,
                "Managed provider runtime is not configured",
            )
        return context.provider_runtime.refresh(force=True)

    return app
